const { contextBridge, ipcRenderer } = require('electron');

const listener = (channel) => (callback) => {
  const handler = (_event, data) => callback(data);
  ipcRenderer.on(channel, handler);
  return () => ipcRenderer.removeListener(channel, handler);
};

contextBridge.exposeInMainWorld('api', {
  getConfig: () => ipcRenderer.invoke('config:get'),
  getI18n: () => ipcRenderer.invoke('i18n:get'),
  saveConfig: (config) => ipcRenderer.invoke('config:save', config),
  exportConfig: () => ipcRenderer.invoke('config:export'),
  importConfig: () => ipcRenderer.invoke('config:import'),
  press: (index, rect) => ipcRenderer.invoke('deck:press', index, rect),
  hideDeck: () => ipcRenderer.send('deck:hide'),
  resetDeckPosition: () => ipcRenderer.send('deck:resetPosition'),
  turnPage: (delta) => ipcRenderer.send('deck:turnPage', delta),
  closePopup: () => ipcRenderer.send('deck:closePopup'),
  deckPointer: (index) => ipcRenderer.send('deck:pointer', index),
  resizeDeck: (phase) => ipcRenderer.send('deck:resize', phase),
  setDeckScale: (scale) => ipcRenderer.send('deck:setScale', scale),
  previewDeckScale: (scale) => ipcRenderer.send('deck:previewScale', scale),
  openEditor: (buttonIndex) => ipcRenderer.send('editor:open', buttonIndex),
  pauseHotkey: (paused) => ipcRenderer.send('hotkey:pause', paused),
  pickFile: (kind) => ipcRenderer.invoke('dialog:pick', kind),
  programIcon: (target) => ipcRenderer.invoke('icon:fromProgram', target),
  listIcons: () => ipcRenderer.invoke('icons:list'),
  streamState: () => ipcRenderer.invoke('stream:state'),
  streamReconnect: () => ipcRenderer.invoke('stream:reconnect'),
  streamScenes: () => ipcRenderer.invoke('stream:scenes'),
  streamVerticalScenes: () => ipcRenderer.invoke('stream:verticalScenes'),
  streamInputs: () => ipcRenderer.invoke('stream:inputs'),
  streamSources: (scene, vertical) => ipcRenderer.invoke('stream:sources', scene, vertical),
  getUpdate: () => ipcRenderer.invoke('update:get'),
  remoteStatus: () => ipcRenderer.invoke('remote:get'),
  setRemoteEnabled: (enabled) => ipcRenderer.invoke('remote:setEnabled', enabled),
  remoteQr: () => ipcRenderer.invoke('remote:qr'),
  newRemoteKey: () => ipcRenderer.invoke('remote:newKey'),
  setRemoteMaxPhones: (max) => ipcRenderer.invoke('remote:setMaxPhones', max),
  installUpdate: () => ipcRenderer.send('update:install'),
  hueStatus: () => ipcRenderer.invoke('hue:status'),
  hueDiscover: () => ipcRenderer.invoke('hue:discover'),
  huePair: (ip) => ipcRenderer.invoke('hue:pair', ip),
  hueForget: () => ipcRenderer.invoke('hue:forget'),
  hueLights: () => ipcRenderer.invoke('hue:lights'),
  onConfig: listener('config:changed'),
  onStreamState: listener('stream:state'),
  onDeckShow: listener('deck:show'),
  onDeckHidden: listener('deck:hidden'),
  onDeckPage: listener('deck:page'),
  onDeckPopup: listener('deck:popup'),
  onDeckScale: listener('deck:scale'),
  onAudio: listener('audio:toggle'),
  onEditorSelect: listener('editor:select'),
  onUpdate: listener('update:available'),
});
